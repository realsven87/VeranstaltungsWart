const { chromium } = require('playwright');
(async () => {
    const browser = await chromium.launch({ headless: true });
    const page = await browser.newPage();
    const base = 'http://127.0.0.1:8080';
    await page.goto(base + '/wp-login.php');
    await page.locator('#user_login').fill('admin');
    await page.locator('#user_pass').fill('test-only-password');
    await Promise.all([page.waitForURL('**/wp-admin/**'), page.locator('#wp-submit').click()]);
    const url = base + '/wp-admin/admin.php?page=vw_settings';
    await page.goto(url);
    const input = page.locator('#vw_retention_days');
    if (await input.inputValue() !== '90') throw new Error('Default retention missing');
    await input.fill('37');
    await Promise.all([page.waitForURL('**/admin.php?page=vw_settings&settings-updated=true'), page.locator('#submit').click()]);
    await page.reload();
    if (await input.inputValue() !== '37') throw new Error('Retention not persisted');
    const fields = await page.locator('form').evaluate(form => Object.fromEntries(new FormData(form)));
    const invalid = await page.request.post(base + '/wp-admin/options.php', { form: { ...fields, vw_retention_days: '-1' } });
    if (!invalid.ok()) throw new Error('Invalid-value request failed unexpectedly');
    await page.goto(url);
    if (await input.inputValue() !== '37') throw new Error('Invalid value overwrote retention');
    const badNonce = await page.request.post(base + '/wp-admin/options.php', { form: { ...fields, _wpnonce: 'invalid', vw_retention_days: '1' } });
    if (badNonce.status() !== 403) throw new Error('Invalid nonce accepted');
    await page.goto(url);
    if (await input.inputValue() !== '37') throw new Error('Invalid nonce changed retention');
    await input.fill('90');
    await Promise.all([page.waitForURL('**/admin.php?page=vw_settings&settings-updated=true'), page.locator('#submit').click()]);
    await browser.close();
    console.log('PASS: retention settings save, persist, reject invalid values and invalid nonces');
})().catch(error => { console.error(error); process.exit(1); });
