const { chromium } = require('playwright');
const fs = require('node:fs');
(async () => {
    const browser = await chromium.launch({ headless: true });
    const page = await browser.newPage();
    const { id } = JSON.parse(fs.readFileSync('/tmp/vw-questions-fixture.json', 'utf8'));
    const base = 'http://127.0.0.1:8080';
    await page.goto(base + '/?p=' + id);
    const form = page.locator('.vw-registration-container form');
    await form.locator('button[type=submit]').waitFor();
    const food = person => form.locator(`[data-vw-question="food"][data-vw-person="${person}"]`);
    const extras = (person, value) => form.locator(`[data-vw-question="bus"][data-vw-person="${person}"][value="${value}"]`);
    await form.locator('[name=guests]').selectOption('2');
    await food(0).selectOption('vegan');
    await food(1).selectOption('meat');
    await food(2).selectOption('vegan');
    await extras(0, 'bus').check();
    await extras(1, 'tour').check();
    await extras(2, 'bus').check();
    await extras(2, 'tour').check();
    await form.locator('[data-vw-question=note]').fill('Gruppenwunsch <script>alert(1)</script>');
    await form.locator('[data-vw-question=group]').selectOption('yes');
    await form.locator('[name=guests]').selectOption('1');
    if (await food(2).count()) throw new Error('Removed guest still in live form');
    await form.locator('[name=guests]').selectOption('2');
    if (await food(2).inputValue() !== 'vegan') throw new Error('Guest answers lost when toggling count');
    await form.locator('[name=guests]').selectOption('1');
    const raw = await form.evaluate(form => Object.fromEntries(new FormData(form)));
    const invalid = await page.request.post(base + '/wp-admin/admin-post.php', { form: { ...raw, first_name: 'Test', last_name: 'Person', email: 'invalid-answers@example.org', gdpr_consent: '1', vw_answers: '{}' } });
    if (!invalid.url().includes('reg_error=invalid_answers')) throw new Error('Server accepted missing required answers');
    await form.locator('[name=first_name]').fill('Fragen');
    await form.locator('[name=last_name]').fill('Browser');
    const email = 'question-browser-' + Date.now() + '@example.org';
    await form.locator('[name=email]').fill(email);
    await form.locator('[name=gdpr_consent]').check();
    await page.setViewportSize({ width: 390, height: 900 });
    if (await form.evaluate(el => el.scrollWidth > el.clientWidth + 2)) throw new Error('Questions overflow mobile form');
    await page.screenshot({ path: '/tmp/vw-screenshots/questions-mobile.png', fullPage: true });
    const submitted = page.waitForRequest(req => req.method() === 'POST' && req.url().includes('admin-post.php'));
    await Promise.all([page.waitForURL('**/*reg=pending*'), form.locator('button[type=submit]').click()]);
    const payload = new URLSearchParams((await submitted).postData());
    const answers = JSON.parse(payload.get('vw_answers'));
    if (answers.food['2'] !== undefined || answers.food['1'] !== 'meat' || answers.group.registration !== 'yes') throw new Error('Wrong person/group payload');
    // View saved answers with existing event permissions and aggregate by status.
    await page.goto(base + '/wp-login.php');
    await page.locator('#user_login').fill('admin');
    await page.locator('#user_pass').fill('test-only-password');
    await Promise.all([page.waitForURL('**/wp-admin/**'), page.locator('#wp-submit').click()]);
    await page.setViewportSize({ width: 1280, height: 900 });
    await page.goto(base + '/wp-admin/admin.php?page=vw_dashboard&vw_summary_event=' + id);
    const row = page.locator('tr').filter({ hasText: email });
    await row.locator('summary').click();
    const text = await row.innerText();
    if (!text.includes('Hauptperson – Essen: Vegan') || !text.includes('Begleitperson 1 – Essen: Fleisch') || text.includes('Begleitperson 2')) throw new Error('Stored answer snapshot incorrect');
    await page.getByRole('heading', { name: 'Auswertung der Zusatzfragen', exact: true }).waitFor();
    await page.screenshot({ path: '/tmp/vw-screenshots/questions-dashboard.png', fullPage: true });
    // Real question configuration UI, saved independently of the post.
    await page.goto(base + '/wp-admin/post.php?post=' + id + '&action=edit');
    await page.waitForFunction(() => window.wp && wp.blocks && wp.blocks.getBlockType('veranstaltungswart/registration'));
    await page.waitForFunction(id => wp.data.select('core/editor').getCurrentPostId() === id && wp.data.select('core/block-editor').getBlocks().length > 0, id);
    await page.evaluate(() => {
        wp.data.dispatch('core/edit-post').openGeneralSidebar('edit-post/block');
        if (wp.data.select('core/edit-post').isFeatureActive('welcomeGuide')) wp.data.dispatch('core/edit-post').toggleFeature('welcomeGuide');
        wp.data.dispatch('core/block-editor').resetBlocks([wp.blocks.createBlock('veranstaltungswart/registration')]);
        wp.data.dispatch('core/block-editor').selectBlock(wp.data.select('core/block-editor').getBlocks()[0].clientId);
    });
    await page.getByRole('button', { name: 'Zentrale Veranstaltungseinstellungen', exact: true }).click();
    await page.getByRole('button', { name: 'Frage hinzufügen', exact: true }).click();
    const question = page.locator('.vw-question-config:visible').last();
    await question.getByLabel('Bezeichnung', { exact: true }).fill('Weitere Wünsche');
    await question.getByLabel('Feldtyp', { exact: true }).selectOption('text');
    await question.getByLabel('Abfrage', { exact: true }).selectOption('registration');
    const savedResponse = page.waitForResponse(r => r.request().method() === 'POST' && decodeURIComponent(r.url()).includes('/veranstaltungswart/v1/settings/'));
    await page.getByRole('button', { name: 'Veranstaltungseinstellungen speichern', exact: true }).click();
    const response = await savedResponse;
    const settings = await response.json();
    if (!response.ok() || settings.vw_questions.at(-1).label !== 'Weitere Wünsche' || settings.vw_questions.at(-1)._new) throw new Error('Question editor failed to save stable schema');
    await page.goto(base + '/?p=' + id);
    if (await page.getByRole('textbox', { name: 'Weitere Wünsche', exact: true }).count() < 1) throw new Error('Saved question absent from frontend');
    await browser.close();
    console.log('PASS: question editor, numbered guests, validation, stored answers, dashboard and mobile form');
})().catch(error => { console.error(error); process.exit(1); });
